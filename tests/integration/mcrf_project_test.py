"""mcrf_project: create, run and package a game with the engine's own interpreter (#420).

mcrf-init.sh copied the packaging rules into each game's Makefile when it made the project,
so every project made before the Python 3.15 move kept packaging libpython3.14. The rules
now live in the engine (mcrf_project.runtime), shared with tools/package.sh, and every
version-dependent name is read from the engine. This drives the real commands as a user
would, with no display (#451), and checks the packages.
"""
import os
import subprocess
import sys
import tarfile
import tempfile
import zipfile
from pathlib import Path

failures = []


def check(cond, msg):
    print(("  ok: " if cond else "FAIL: ") + msg)
    if not cond:
        failures.append(msg)


ENGINE = Path(sys.executable).resolve()
PY = "%d.%d" % sys.version_info[:2]
ENV = {k: v for k, v in os.environ.items() if k not in ("DISPLAY", "WAYLAND_DISPLAY")}
ENV["ALSOFT_DRIVERS"] = "null"


def tool(*args, cwd):
    out = subprocess.run([str(ENGINE), "-m", "mcrf_project"] + list(args), cwd=str(cwd),
                         capture_output=True, text=True, timeout=300, env=ENV)
    return out.returncode, out.stdout + out.stderr


with tempfile.TemporaryDirectory() as tmp:
    tmp = Path(tmp)
    game = tmp / "my-game"

    # --- init ---
    rc, out = tool("init", "my-game", cwd=tmp)
    check(rc == 0, "init exits 0 with no display (%d)%s" % (rc, "" if rc == 0 else "\n" + out[-400:]))
    for rel in ("scripts/game.py", "assets/JetbrainsMono.ttf", "assets/kenney_tinydungeon.png",
                "Makefile", ".mcrf.mk", ".gitignore", "VERSION", "pyrightconfig.json",
                "typings/mcrfpy.pyi"):
        check((game / rel).is_file(), "init creates %s" % rel)
    check(not (game / "save").exists() and not (tmp / "save").exists(),
          "init doesn't leave a save/ directory behind")
    makefile = (game / "Makefile").read_text()
    check("3.1" not in makefile and str(ENGINE) not in makefile,
          "the Makefile names no Python version and no engine path")
    check((game / ".mcrf.mk").read_text().strip() == "MCRF := %s" % ENGINE, ".mcrf.mk names this engine")
    check('"pythonVersion": "%s"' % PY in (game / "pyrightconfig.json").read_text(),
          "pyrightconfig targets the engine's Python %s" % PY)
    check(".mcrf.mk" in (game / ".gitignore").read_text(), ".mcrf.mk is ignored by git")

    # Re-running keeps the game's files and refreshes the engine's.
    (game / "scripts" / "game.py").write_text(
        "import sys, helper\nprint('RAN', helper.VALUE)\nsys.exit(0)\n")
    (game / "scripts" / "helper.py").write_text("VALUE = 'from the project'\n")
    (game / "VERSION").write_text("1.2.3\n")
    rc, out = tool("init", cwd=game)
    check(rc == 0 and "RAN" in (game / "scripts" / "game.py").read_text(),
          "re-running init keeps the game's own game.py")

    # A project made by mcrf-init.sh: its Makefile is replaced, a hand-written one is not.
    old = tmp / "old-game"
    (old / "scripts").mkdir(parents=True)
    (old / "scripts" / "game.py").write_text("")
    (old / "Makefile").write_text("# McRogueFace Game Project Makefile\n# Generated by mcrf-init\n"
                                  "\tfor lib in libpython3.14.so.1.0\n")
    rc, out = tool("init", cwd=old)
    check(rc == 0 and "3.14" not in (old / "Makefile").read_text(),
          "init replaces an mcrf-init.sh Makefile")
    custom = tmp / "custom"
    (custom / "scripts").mkdir(parents=True)
    (custom / "Makefile").write_text("all:\n\techo mine\n")
    tool("init", cwd=custom)
    check((custom / "Makefile").read_text() == "all:\n\techo mine\n", "init leaves a hand-written Makefile alone")

    # --- run: the game from the project, importing its own modules (#452) ---
    rc, out = tool("run", "--", "--headless", cwd=game)
    check(rc == 0 and "RAN from the project" in out, "run runs scripts/game.py, which imports its own module")

    rc, out = tool("info", cwd=game)
    check(rc == 0 and "my-game 1.2.3" in out and PY in out, "info names the project and the engine's Python")

    # --- dist: Linux ---
    rc, out = tool("dist", "--platform", "linux", cwd=game)
    tar_path = game / "dist" / "my-game-1.2.3-Linux.tar.gz"
    check(rc == 0 and tar_path.is_file(), "dist builds %s%s" % (tar_path.name, "" if rc == 0 else "\n" + out[-400:]))
    if tar_path.is_file():
        with tarfile.open(tar_path) as tar:
            names = set(n.split("/", 1)[1] for n in tar.getnames() if "/" in n)
            extract = tmp / "linux-pkg"
            tar.extractall(extract)
        for rel in ("mcrogueface", "run.sh", "lib/libpython%s.so.1.0" % PY, "lib/libtcod.so.2",
                    "lib/Python/Lib/os.py", "lib/Python/Lib/mcrf_project/__main__.py",
                    "scripts/game.py", "scripts/helper.py", "assets/kenney_tinydungeon.png"):
            check(rel in names, "the Linux package has %s" % rel)
        check(any(n.startswith("lib/Python/lib.linux-") and n.endswith("-%s" % PY) for n in names),
              "the Linux package has the %s extension modules" % PY)
        stale = sorted(n for n in names if "python3." in n and ("python%s" % PY) not in n
                       and ("-%s" % PY) not in n)
        check(not stale, "no other Python's files ship %s" % stale[:3])
        check(not any("__pycache__" in n or "/idlelib/" in n or n.startswith("lib/Python/Lib/test/")
                      for n in names), "no caches, tests or idlelib ship")
        check(not any(n.startswith(("Makefile", "VERSION", "typings", ".mcrf")) for n in names),
              "only the game's assets/ and scripts/ ship from the project")

        # The package runs on its own: its libraries, its stdlib, the game's scripts.
        pkg = extract / "my-game-1.2.3-Linux"
        probe = pkg / "probe.py"
        probe.write_text("import sys, os, helper, socket, mcrf_project\n"
                         "print('PKG', helper.VALUE, socket.__file__.startswith(%r))\n"
                         "sys.exit(0)\n" % str(pkg))
        env = {k: v for k, v in ENV.items() if k not in ("LD_LIBRARY_PATH", "PYTHONPATH", "PYTHONHOME")}
        out = subprocess.run([str(pkg / "mcrogueface"), "--headless", "--exec", str(probe)], cwd=str(pkg),
                             capture_output=True, text=True, timeout=60, env=env)
        ran = out.returncode == 0 and "PKG from the project True" in out.stdout
        check(ran, "the extracted package runs from its own stdlib (rc=%d)%s"
              % (out.returncode, "" if ran else "\n" + (out.stdout + out.stderr)[-600:]))

    # --- dist: Windows, when this tree has a Windows build ---
    windows = ENGINE.parent.parent / "build-windows"
    if (windows / "mcrogueface.exe").is_file():
        rc, out = tool("dist", "--platform", "windows", cwd=game)
        zip_path = game / "dist" / "my-game-1.2.3-Windows.zip"
        check(rc == 0 and zip_path.is_file(), "dist --platform windows builds %s" % zip_path.name)
        if zip_path.is_file():
            names = set(n.split("/", 1)[1] for n in zipfile.ZipFile(zip_path).namelist() if "/" in n)
            nodot = PY.replace(".", "")
            for rel in ("mcrogueface.exe", "python%s.dll" % nodot, "lib/Python/Lib/os.py",
                        "lib/Python/Lib/mcrf_project/runtime.py", "scripts/game.py",
                        "assets/JetbrainsMono.ttf"):
                check(rel in names, "the Windows package has %s" % rel)
            check(any(n.startswith("lib/Python/DLLs/_socket") for n in names),
                  "the Windows package has the extension modules (lib/Python/DLLs)")
            check(not any(n.endswith((".so", ".so.1.0")) for n in names), "no Linux libraries in it")
    else:
        print("  note: no build-windows/ here; the Windows package isn't checked")

    # --- errors say what's wrong ---
    rc, out = tool("dist", cwd=tmp)
    check(rc == 1 and "not a game project" in out and "Traceback" not in out,
          "dist outside a project fails with a message")
    rc, out = tool("init", cwd=ENGINE.parent)
    check(rc == 1 and "engine's own directory" in out, "init refuses the engine's own directory")
    rc, out = tool("dist", "--platform", "windows", "--engine", str(ENGINE.parent), cwd=game)
    check(rc == 1 and "not windows" in out, "a Linux engine can't make a Windows package")

if failures:
    print("FAIL: %d check(s)" % len(failures))
    sys.exit(1)
print("PASS")
sys.exit(0)
