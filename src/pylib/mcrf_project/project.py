"""A game project: scripts/ and assets/, and the files that run and package it.

    my-game/
      scripts/game.py      the game (sys.path[0] when it runs, #452)
      assets/              its assets, starting with the engine's default font and texture
      VERSION              the game's version, used in package names
      mcrf.toml            optional settings: which engine, the requirements (see CONFIG_KEYS)
      .venv/               installed requirements (`deps`), shipped by `dist` as venv/
      Makefile             `make run`, `make dist`, ... calling the engine
      .mcrf.mk             which engine (local, ignored by git)
      typings/mcrfpy.pyi   type stubs for the editor (refreshed by `init`)
      pyrightconfig.json

Nothing in a project names a path on the machine that made it except .mcrf.mk, which git
ignores, so a project can be cloned and used with any engine.
"""
import json
import os
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

from .errors import ProjectError
from . import deps
from . import runtime as rt

# Copied into a new project's assets/: the files the engine loads when a Font or Texture
# isn't given (mcrfpy.default_font, mcrfpy.default_texture).
DEFAULT_ASSETS = ("JetbrainsMono.ttf", "kenney_tinydungeon.png")

STARTER_GAME = '''"""{name} - a McRogueFace game."""
import mcrfpy

scene = mcrfpy.Scene("title")

scene.children.append(mcrfpy.Caption(
    text="{name}", pos=(512, 300), font_size=48, fill_color=(255, 255, 255)))
scene.children.append(mcrfpy.Caption(
    text="Press ESC to quit", pos=(512, 400), font_size=24, fill_color=(180, 180, 180)))


def on_key(key, state):
    if key == mcrfpy.Key.ESCAPE and state == mcrfpy.InputState.PRESSED:
        mcrfpy.exit()


scene.on_key = on_key
mcrfpy.current_scene = scene
'''

CONFIG_NAME = "mcrf.toml"
# What mcrf.toml may hold, and the type of each. An unknown key is an error, so a typo
# can't silently do nothing.
CONFIG_KEYS = {
    "engine": str,             # directory of the engine to use (#500); prefer $MCROGUEFACE
    "engine-version": str,     # which per-user install to use, e.g. "0.3.3" (#500)
    "requirements": list,      # pip requirement strings, installed by `deps` (#499)
    "requirements-file": str,  # a pip requirements file, relative to the project (#499)
}
CONFIG_TEMPLATE = """# McRogueFace project settings. Every key is optional.
#
# Which engine runs and packages this project. Without these, mcrf_project uses
# $MCROGUEFACE, then the newest engine under ~/.local/share/mcrogueface/<version>/, then
# the engine running it (`info` says which). Prefer the environment variable to `engine`:
# a path here is a path on one machine.
# engine-version = "0.3.3"
# engine = "/path/to/engine"
#
# Third-party packages, installed into .venv/ by `mcrf_project deps` and shipped by `dist`.
# requirements = ["some-package>=1.0"]
# requirements-file = "requirements.txt"
"""

GITIGNORE = """# McRogueFace game project
.mcrf.mk
.venv/
dist/
build-web/
save/
typings/
__pycache__/
*.pyc
"""

# Every target is the engine running mcrf_project, so packaging rules come from the engine
# in use, not from this file.
MAKEFILE = """# McRogueFace game project. Generated by mcrf_project; safe to edit.
# The engine is set in .mcrf.mk (written by `mcrogueface -m mcrf_project init`), or
# override it: make MCRF=/path/to/mcrogueface run
-include .mcrf.mk
MCRF ?= mcrogueface

.PHONY: run deps dist dist-linux dist-windows dist-web info

run:
\t$(MCRF) -m mcrf_project run

deps:
\t$(MCRF) -m mcrf_project deps

dist:
\t$(MCRF) -m mcrf_project dist

dist-linux:
\t$(MCRF) -m mcrf_project dist --platform linux

dist-windows:
\t$(MCRF) -m mcrf_project dist --platform windows

dist-web:
\t$(MCRF) -m mcrf_project dist --platform web

info:
\t$(MCRF) -m mcrf_project info
"""

# Makefiles mcrf-init.sh wrote, which init replaces (they hardcode a Python version, #420).
LEGACY_MAKEFILE_MARKER = "# Generated by mcrf-init"
MAKEFILE_MARKER = "# McRogueFace game project. Generated by mcrf_project"


class Project:
    def __init__(self, path):
        self.dir = Path(path).resolve()

    @property
    def name(self):
        return self.dir.name

    @property
    def scripts(self):
        return self.dir / "scripts"

    @property
    def assets(self):
        return self.dir / "assets"

    @property
    def version(self):
        try:
            return (self.dir / "VERSION").read_text().strip() or "0.1.0"
        except FileNotFoundError:
            return "0.1.0"

    @property
    def config_path(self):
        return self.dir / CONFIG_NAME

    @property
    def config(self):
        """The validated contents of mcrf.toml ({} if there is none)."""
        if not self.config_path.is_file():
            return {}
        try:
            with open(self.config_path, "rb") as f:
                data = tomllib.load(f)
        except tomllib.TOMLDecodeError as exc:
            raise ProjectError("%s: %s" % (self.config_path, exc))
        for key, value in data.items():
            if key not in CONFIG_KEYS:
                raise ProjectError("%s: unknown key %r (known: %s)"
                                   % (self.config_path, key, ", ".join(CONFIG_KEYS)))
            kind = CONFIG_KEYS[key]
            if not isinstance(value, kind) or (kind is list and not all(isinstance(v, str) for v in value)):
                raise ProjectError("%s: %s must be %s" % (self.config_path, key,
                                   "a list of strings" if kind is list else "a string"))
        return data

    def require(self):
        """Raise unless this is a game project."""
        if not (self.scripts / "game.py").is_file():
            raise ProjectError("%s is not a game project (no scripts/game.py); "
                               "create one with: mcrogueface -m mcrf_project init" % self.dir)

    # --- init ---------------------------------------------------------------------------

    def init(self, engine, log):
        """Create the project, or bring an existing one up to date. Never overwrites the
        game's own files."""
        if (self.dir == engine.dir or engine.dir in self.dir.parents
                or self.dir == engine.source_root):
            raise ProjectError("can't make a game project in the engine's own directory (%s)"
                               % self.dir)
        self.scripts.mkdir(parents=True, exist_ok=True)
        self.assets.mkdir(parents=True, exist_ok=True)

        game = self.scripts / "game.py"
        if not game.exists():
            game.write_text(STARTER_GAME.format(name=self.name))
            log("created scripts/game.py")

        for asset in DEFAULT_ASSETS:
            if not (self.assets / asset).exists():
                src = engine.dir / "assets" / asset
                if not src.is_file():
                    raise ProjectError("the engine's default asset %s is missing" % src)
                shutil.copy2(src, self.assets / asset)
                log("copied assets/%s" % asset)

        self._write_once(".gitignore", GITIGNORE, log)
        self._write_once("VERSION", "0.1.0\n", log)
        self._write_once(CONFIG_NAME, CONFIG_TEMPLATE, log)

        makefile = self.dir / "Makefile"
        existing = makefile.read_text() if makefile.exists() else None
        head = (existing or "").splitlines()[:3]
        legacy = LEGACY_MAKEFILE_MARKER in head
        if existing is None or legacy or (head and head[0].startswith(MAKEFILE_MARKER)):
            if existing != MAKEFILE:
                makefile.write_text(MAKEFILE)
                log("replaced the Makefile mcrf-init.sh wrote" if legacy else "wrote Makefile")
        else:
            log("left Makefile alone (not generated by mcrf_project)")

        (self.dir / ".mcrf.mk").write_text("MCRF := %s\n" % _make_quote(engine.exe))
        log("engine: %s" % engine.exe)

        self._write_stubs(engine, log)
        self._write_once("pyrightconfig.json", json.dumps({
            "include": ["scripts"],
            "stubPath": "typings",
            "pythonVersion": engine.python_version,
            "typeCheckingMode": "basic",
            "reportMissingModuleSource": False,
        }, indent=4) + "\n", log)

        if (self.dir / "build").is_dir() and (self.dir / "build" / "mcrogueface").is_symlink():
            log("build/ holds links from mcrf-init.sh and is no longer used; it can be deleted")

    def _write_once(self, name, text, log):
        path = self.dir / name
        if not path.exists():
            path.write_text(text)
            log("created %s" % name)

    def _write_stubs(self, engine, log):
        # A release package ships the stubs in docs/; a source tree has them in stubs/.
        candidates = [engine.dir / "docs" / "mcrfpy.pyi"]
        if engine.source_root:
            candidates.append(engine.source_root / "stubs" / "mcrfpy.pyi")
        for stub in candidates:
            if stub.is_file():
                (self.dir / "typings").mkdir(exist_ok=True)
                shutil.copy2(stub, self.dir / "typings" / "mcrfpy.pyi")
                log("typings/mcrfpy.pyi from %s" % stub)
                return
        log("no mcrfpy.pyi found beside the engine (looked in: %s); editor completion "
            "for mcrfpy is unavailable" % ", ".join(str(c) for c in candidates))

    # --- run ----------------------------------------------------------------------------

    def run(self, engine, args):
        """Run the game: the engine in the project directory loads scripts/game.py."""
        self.require()
        deps.require_installed(self, engine)
        return subprocess.call([str(engine.exe)] + list(args), cwd=self.dir)

    # --- dist ---------------------------------------------------------------------------

    def dist(self, engine, out_dir, log):
        """Package the game with `engine`'s runtime. Returns the archive path."""
        self.require()
        deps.require_installed(self, engine)  # before anything is made: fail early
        name = "%s-%s-%s" % (self.name, self.version, engine.title)
        staged = rt.fresh_dir(Path(out_dir) / name)
        log("packaging %s with the %s engine at %s" % (name, engine.title, engine.dir))
        engine.stage(staged)
        rt.copy_content(staged, self.assets, self.scripts)
        deps.stage(self, engine, staged)
        return rt.archive(staged, engine.platform)

    def dist_web(self, engine, out_dir, log, jobs=None):
        """Build the game for the browser from the engine's source tree (needs emsdk)."""
        self.require()
        if deps.requirements(self):
            raise ProjectError("dependencies (mcrf.toml requirements) aren't bundled in web builds")
        root = engine.source_root
        if root is None:
            raise ProjectError("a web build compiles the engine from source; %s is not in an "
                               "engine source tree" % engine.dir)
        for tool in ("emcmake", "emmake"):
            if shutil.which(tool) is None:
                raise ProjectError("%s not found: activate emsdk first (source ~/emsdk/emsdk_env.sh)"
                                   % tool)
        build = self.dir / "build-web"
        log("building for the web in %s" % build)
        _check_call(["emcmake", "cmake", "-S", str(root), "-B", str(build),
                     "-DMCRF_SDL2=ON", "-DMCRF_GAME_SHELL=ON",
                     "-DMCRF_ASSETS_DIR=%s" % self.assets, "-DMCRF_SCRIPTS_DIR=%s" % self.scripts])
        _check_call(["emmake", "make", "-C", str(build), "-j%d" % (jobs or os.cpu_count() or 1)])

        return rt.web_archive(build, Path(out_dir) / ("%s-%s-Web.zip" % (self.name, self.version)))


def _check_call(cmd):
    if subprocess.call(cmd) != 0:
        raise ProjectError("failed: %s" % " ".join(cmd))


def _make_quote(path):
    return str(path).replace(" ", "\\ ")
