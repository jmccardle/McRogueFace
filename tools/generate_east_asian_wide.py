#!/usr/bin/env python3
"""Generate src/EastAsianWide.h: the codepoint ranges whose Unicode East Asian Width is
W (Wide) or F (Fullwidth). Texture.from_font (#547) gives these two tiles.

Uses unicodedata from whichever Python runs this script; the Unicode version is recorded in
the header. Regenerate (and commit the result) when the Unicode version should change:

    python3 tools/generate_east_asian_wide.py > src/EastAsianWide.h
"""
import sys
import unicodedata

ranges = []
start = prev = None
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        wide = False
    else:
        wide = unicodedata.east_asian_width(chr(cp)) in ("W", "F")
    if wide:
        if start is None:
            start = cp
        prev = cp
    elif start is not None:
        ranges.append((start, prev))
        start = None
if start is not None:
    ranges.append((start, prev))

out = sys.stdout
out.write("// Generated by tools/generate_east_asian_wide.py -- do not edit.\n")
out.write(f"// Unicode {unicodedata.unidata_version} East Asian Width W and F ranges (inclusive), sorted.\n")
out.write("#pragma once\n#include <cstdint>\n\n")
out.write(f'constexpr const char* EAST_ASIAN_WIDE_UNICODE_VERSION = "{unicodedata.unidata_version}";\n\n')
out.write("struct EastAsianWideRange { uint32_t lo, hi; };\n")
out.write("constexpr EastAsianWideRange EAST_ASIAN_WIDE_RANGES[] = {\n")
for i in range(0, len(ranges), 4):
    out.write("    " + " ".join(f"{{0x{a:X}, 0x{b:X}}}," for a, b in ranges[i:i + 4]) + "\n")
out.write("};\n")
